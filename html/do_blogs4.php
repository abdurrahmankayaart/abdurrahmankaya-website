<p>Güvenli ölçekleme kuralı: bütçeyi 3-4 günde bir, en fazla yüzde yirmi oranında artırın. Yani günlük 500 TL\'lik bir kampanyayı bir anda 1.500 TL\'ye çıkarmak yerine, kademeli olarak 600, sonra 720 TL şeklinde büyütün. Daha agresif büyümek istiyorsanız, mevcut kampanyayı kopyalayıp yeni bütçeyle ayrı bir kampanya açmak alternatif bir yöntem.</p>

<h2>ROAS: Bütçe Kararlarının Pusulası</h2>
<p>Bütçe kararlarını duygularınıza değil, ROAS\'a (Return on Ad Spend - Reklam Harcama Getirisi) göre verin. ROAS, harcadığınız her 1 TL\'ye karşılık kaç TL gelir elde ettiğinizi gösterir. 4 ROAS, 1 TL harcamaya 4 TL gelir demektir.</p>

<p>Hedef ROAS\'ınız kâr marjınıza bağlı. Kâr marjı düşük bir üründe 4-5 ROAS gerekirken, yüksek marjlı bir hizmette 2 ROAS bile kârlı olabilir. Önce başabaş ROAS\'ınızı hesaplayın, ardından bunun üzerindeki kampanyaları ölçekleyip altındakileri durdurun.</p>

